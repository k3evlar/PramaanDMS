"""Create the local secrets for the Docker stack.

Usage (from the repo root):
    python tools/setup_env.py            # first time
    python tools/setup_env.py --force    # replace existing secrets (then also delete the
                                         # Docker volumes: docker compose down -v)

Writes (all git-ignored):
    .env                          copy of .env.example with every "change-me" replaced
    docker/secrets/valkey.conf    Valkey config holding the queue password
    docker/secrets/seaweedfs_s3.json   S3 identities for SeaweedFS

Secrets come from Python's `secrets` module (a CSPRNG, ASVS V11.5.1): 256-bit URL-safe
values for passwords and tokens. Nothing is printed to the screen.
"""

from __future__ import annotations

import argparse
import json
import os
import secrets
import stat
import sys
from pathlib import Path

PLACEHOLDER = "change-me"


def parse_env(text: str) -> list[tuple[str, str] | str]:
    """Keep comments and blank lines as strings; KEY=VALUE lines as tuples."""
    out: list[tuple[str, str] | str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            out.append(line)
            continue
        if "=" not in line:
            raise ValueError(f"bad line in env template: {line!r}")
        key, value = line.split("=", 1)
        out.append((key.strip(), value.strip()))
    return out


def new_value(key: str) -> str:
    if key.endswith("_ACCESS_KEY"):
        # S3 access key IDs: 20 upper-case letters and digits, like AWS-style IDs.
        alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
        return "PRM" + "".join(secrets.choice(alphabet) for _ in range(17))
    return secrets.token_urlsafe(32)  # 256 bits, URL-safe (used inside connection URLs)


def _write_private(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    if os.name == "posix":
        path.chmod(stat.S_IRUSR | stat.S_IWUSR)


def build(root: Path, force: bool = False) -> dict[str, str]:
    template = root / ".env.example"
    env_path = root / ".env"
    if env_path.exists() and not force:
        raise FileExistsError(".env already exists. Use --force to replace it (and run "
                              "`docker compose down -v`, because existing volumes keep the old passwords).")
    entries = parse_env(template.read_text(encoding="utf-8"))
    values: dict[str, str] = {}
    lines: list[str] = []
    for e in entries:
        if isinstance(e, str):
            lines.append(e)
            continue
        key, value = e
        if value == PLACEHOLDER:
            value = new_value(key)
        values[key] = value
        lines.append(f"{key}={value}")
    _write_private(env_path, "\n".join(lines) + "\n")

    secrets_dir = root / "docker" / "secrets"
    _write_private(secrets_dir / "valkey.conf",
                   "# Generated by tools/setup_env.py. Do not commit.\n"
                   "bind 0.0.0.0\nport 6379\nprotected-mode yes\nappendonly yes\n"
                   f"requirepass {values['VALKEY_PASSWORD']}\n")
    s3 = {"identities": [
        {"name": "pramaan_admin",
         "credentials": [{"accessKey": values["PRAMAAN_S3_ADMIN_ACCESS_KEY"],
                          "secretKey": values["PRAMAAN_S3_ADMIN_SECRET_KEY"]}],
         "actions": ["Admin", "Read", "List", "Tagging", "Write"]},
        {"name": "pramaan_app",
         "credentials": [{"accessKey": values["PRAMAAN_S3_APP_ACCESS_KEY"],
                          "secretKey": values["PRAMAAN_S3_APP_SECRET_KEY"]}],
         "actions": ["Read", "List", "Tagging", "Write"]},
    ]}
    _write_private(secrets_dir / "seaweedfs_s3.json", json.dumps(s3, indent=2) + "\n")
    return values


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate .env and service secrets for the Docker stack.")
    ap.add_argument("--force", action="store_true", help="replace existing secrets")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = ap.parse_args(argv)
    try:
        values = build(args.root, args.force)
    except (FileExistsError, ValueError, KeyError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    generated = sum(1 for k in values if k.endswith(("PASSWORD", "TOKEN", "_KEY")))
    print(f"wrote .env and docker/secrets/ ({generated} secrets generated; values not shown)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
